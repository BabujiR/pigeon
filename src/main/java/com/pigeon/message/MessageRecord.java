package com.pigeon.message;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.Id;
import jakarta.persistence.PostLoad;
import jakarta.persistence.PostPersist;
import jakarta.persistence.Table;
import jakarta.persistence.Transient;
import java.time.Duration;
import java.time.Instant;
import java.util.Map;
import java.util.UUID;
import org.hibernate.annotations.JdbcTypeCode;
import org.hibernate.type.SqlTypes;
import org.springframework.data.domain.Persistable;

/**
 * One email, from accepted request to final outcome.
 *
 * <p>Review notes: the id is generated by the application (it is the requestId we return), so
 * the entity implements {@link Persistable}. Without it Spring Data would treat every new
 * record as existing and run a SELECT before each INSERT. State changes go through named
 * methods ({@link #markQueued}, {@link #markSuppressed}) instead of setters, so every
 * transition is visible in one place.
 */
@Entity
@Table(name = "message_record")
public class MessageRecord implements Persistable<UUID> {

    @Id
    private UUID id;

    @Column(name = "correlation_id", nullable = false)
    private String correlationId;

    @Column(name = "template_id", nullable = false)
    private String templateId;

    @Column(name = "template_version", nullable = false)
    private int templateVersion;

    @Column(nullable = false)
    private String recipient;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false)
    private MessageStream stream;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false)
    private MessageStatus status;

    /** Merge values. Contains PII: stored for rendering, never logged, never put on a queue. */
    @JdbcTypeCode(SqlTypes.JSON)
    @Column(nullable = false, columnDefinition = "jsonb")
    private Map<String, String> variables;

    @Column(name = "configuration_set")
    private String configurationSet;

    @Column(name = "ses_message_id")
    private String sesMessageId;

    @Column(name = "attempt_count", nullable = false)
    private int attemptCount;

    @Column(name = "last_error", columnDefinition = "text")
    private String lastError;

    @Column(name = "created_at", nullable = false, columnDefinition = "timestamptz")
    private Instant createdAt;

    @Column(name = "updated_at", nullable = false, columnDefinition = "timestamptz")
    private Instant updatedAt;

    @Column(name = "sent_at", columnDefinition = "timestamptz")
    private Instant sentAt;

    /** While in the future, one worker owns the send. See V5__send_lease.sql. */
    @Column(name = "send_lease_until", columnDefinition = "timestamptz")
    private Instant sendLeaseUntil;

    @Transient
    private boolean isNew = true;

    protected MessageRecord() {
        // for JPA
    }

    public static MessageRecord accept(UUID id, String correlationId, String templateId, int templateVersion,
                                       String recipient, MessageStream stream, Map<String, String> variables,
                                       String configurationSet, Instant now) {
        MessageRecord m = new MessageRecord();
        m.id = id;
        m.correlationId = correlationId;
        m.templateId = templateId;
        m.templateVersion = templateVersion;
        m.recipient = recipient;
        m.stream = stream;
        m.status = MessageStatus.ACCEPTED;
        m.variables = Map.copyOf(variables);
        m.configurationSet = configurationSet;
        m.createdAt = now;
        m.updatedAt = now;
        return m;
    }

    public void markQueued(Instant now) {
        requireStatus(MessageStatus.ACCEPTED);
        this.status = MessageStatus.QUEUED;
        this.updatedAt = now;
    }

    /** At accept time (Phase 2) or at send time, if the address was suppressed in between. */
    public void markSuppressed(Instant now) {
        requireStatus(MessageStatus.ACCEPTED, MessageStatus.QUEUED);
        this.status = MessageStatus.SUPPRESSED;
        this.sendLeaseUntil = null;
        this.updatedAt = now;
    }

    public boolean isLeasedAt(Instant now) {
        return sendLeaseUntil != null && sendLeaseUntil.isAfter(now);
    }

    /** A worker takes ownership of the send for {@code lease}; counts as one attempt. */
    public void claimForSend(Instant now, Duration lease) {
        requireStatus(MessageStatus.QUEUED);
        this.attemptCount++;
        this.sendLeaseUntil = now.plus(lease);
        this.updatedAt = now;
    }

    public void markSent(String sesMessageId, Instant now) {
        requireStatus(MessageStatus.QUEUED);
        this.status = MessageStatus.SENT;
        this.sesMessageId = sesMessageId;
        this.sentAt = now;
        this.sendLeaseUntil = null;
        this.lastError = null;
        this.updatedAt = now;
    }

    /** A retryable failure: stays QUEUED, releases the lease so the next delivery can try again. */
    public void recordSendFailure(String error, Instant now) {
        this.lastError = truncate(error);
        this.sendLeaseUntil = null;
        this.updatedAt = now;
    }

    /** Permanent failure, or retries exhausted. Nothing more will be attempted. */
    public void markFailed(String error, Instant now) {
        requireStatus(MessageStatus.ACCEPTED, MessageStatus.QUEUED);
        this.status = MessageStatus.FAILED;
        this.lastError = truncate(error);
        this.sendLeaseUntil = null;
        this.updatedAt = now;
    }

    /**
     * Applies a delivery outcome reported by SES (Phase 4). Events can arrive out of order and
     * more than once, so the status only ever moves forward:
     * SENT -> DELIVERED -> BOUNCED -> COMPLAINED. A late Delivery after a Complaint changes nothing.
     *
     * @return true if the status changed
     */
    public boolean applyOutcome(MessageStatus outcome, Instant now) {
        if (outcomeRank(status) < 0 || outcomeRank(outcome) <= outcomeRank(status)) {
            return false;
        }
        this.status = outcome;
        this.updatedAt = now;
        return true;
    }

    /** SES rejected the message after accepting it (Reject or Rendering Failure event). */
    public boolean markRejectedBySes(String reason, Instant now) {
        if (status != MessageStatus.SENT) {
            return false;
        }
        this.status = MessageStatus.FAILED;
        this.lastError = truncate(reason);
        this.updatedAt = now;
        return true;
    }

    private static int outcomeRank(MessageStatus s) {
        return switch (s) {
            case SENT -> 1;
            case DELIVERED -> 2;
            case BOUNCED -> 3;
            case COMPLAINED -> 4;
            default -> -1;    // ACCEPTED, QUEUED, SUPPRESSED, FAILED: SES outcomes do not apply
        };
    }

    private static String truncate(String error) {
        if (error == null) {
            return null;
        }
        return error.length() <= 1000 ? error : error.substring(0, 1000);
    }

    private void requireStatus(MessageStatus... expected) {
        for (MessageStatus e : expected) {
            if (status == e) {
                return;
            }
        }
        throw new IllegalStateException("Message " + id + " is " + status + ", expected one of "
                + java.util.Arrays.toString(expected));
    }

    @PostLoad
    @PostPersist
    void markNotNew() {
        this.isNew = false;
    }

    @Override
    public UUID getId() {
        return id;
    }

    @Override
    public boolean isNew() {
        return isNew;
    }

    public String getCorrelationId() {
        return correlationId;
    }

    public String getTemplateId() {
        return templateId;
    }

    public int getTemplateVersion() {
        return templateVersion;
    }

    public String getRecipient() {
        return recipient;
    }

    public MessageStream getStream() {
        return stream;
    }

    public MessageStatus getStatus() {
        return status;
    }

    public Map<String, String> getVariables() {
        return variables;
    }

    public String getConfigurationSet() {
        return configurationSet;
    }

    public String getSesMessageId() {
        return sesMessageId;
    }

    public int getAttemptCount() {
        return attemptCount;
    }

    public String getLastError() {
        return lastError;
    }

    public Instant getCreatedAt() {
        return createdAt;
    }

    public Instant getUpdatedAt() {
        return updatedAt;
    }

    public Instant getSentAt() {
        return sentAt;
    }

    public Instant getSendLeaseUntil() {
        return sendLeaseUntil;
    }
}
